#!/usr/bin/env node
/**
 * build.js
 *
 * Generates every derived token file from the DTCG JSON in tokens/. The JSON
 * is the only source of truth; nothing written here is edited by hand.
 *
 *   tokens/css/variables-light.css   :root custom properties (all tokens + shadcn aliases)
 *   tokens/css/variables-dark.css    .dark overrides (every variable whose value changes)
 *   tokens/css/tailwind-theme.css    Tailwind v4 @theme mapping onto the variables
 *   tokens/css/proto-lab.css         Tailwind entry: variables + theme + variant + base layer
 *   tokens/dist/tokens.json          Flat records for the docs site and agents
 *   .github/skills/.../tokens.md     CSS variable section of the agent skill reference
 *
 * Usage:
 *   node packages/tokens/build.js           write all outputs
 *   node packages/tokens/build.js --check   fail if any output is stale
 */

'use strict';

const fs   = require('fs');
const path = require('path');
const { TOKENS_DIR, MODES, loadSet, cssVars, contrast } = require('./lib');

const ROOT = path.resolve(TOKENS_DIR, '..');
const PAIRS = require('./contrast-pairs.json');

const HEADER = (what) => [
  '/*',
  ` * Proto-Lab Design System: ${what}`,
  ' * Foundation: CapTech Brand + Fluent 2 Web',
  ' *',
  ' * GENERATED by packages/tokens/build.js from tokens/*.json. Do not edit.',
  ' * Change the JSON and run `npm run tokens:build`.',
  ' */',
  '',
].join('\n');

// ─── Sections (order and grouping of variables in the CSS and docs) ─────────

const SECTIONS = [
  ['Primitive: Brand',             /^color\.primitive\.brand\./],
  ['Primitive: Accent & Tertiary', /^color\.primitive\.(accent|tertiary)\./],
  ['Primitive: Brand Ramp',        /^color\.primitive\.brand-ramp\./],
  ['Primitive: Blue Scale',        /^color\.primitive\.blue-scale\./],
  ['Primitive: Neutral',           /^color\.primitive\.neutral\./],
  ['Primitive: Opacity',           /^color\.primitive\.opacity\./],
  ['Semantic: Neutral',            /^color\.semantic\.neutral\./],
  ['Semantic: Brand',              /^color\.semantic\.brand\./],
  ['Semantic: Status',             /^color\.semantic\.status\./],
  ['Semantic: Chart',              /^color\.semantic\.chart\./],
  ['Semantic: Illustration',       /^color\.semantic\.illustration\./],
  ['Shadow',                       /^(color\.semantic\.shadow|shadow)\./],
  ['Typography',                   /^typography\./],
  ['Spacing',                      /^spacing\./],
  ['Corner Radius',                /^corner-radius\./],
  ['Stroke Width',                 /^stroke-width\./],
  ['Motion',                       /^motion\./],
  ['shadcn Aliases',               /^alias\.shadcn\./],
];

function sectionOf(v) {
  const s = SECTIONS.find(([, re]) => re.test(v.path));
  if (!s) throw new Error(`No section for ${v.path}`);
  return s[0];
}

function grouped(vars) {
  return SECTIONS
    .map(([title]) => [title, vars.filter((v) => sectionOf(v) === title)])
    .filter(([, list]) => list.length);
}

// ─── Load ────────────────────────────────────────────────────────────────────

const sets = Object.fromEntries(MODES.map((m) => [m, loadSet(m)]));
const vars = Object.fromEntries(MODES.map((m) => [m, cssVars(sets[m])]));
const byName = Object.fromEntries(MODES.map((m) => [m, new Map(vars[m].map((v) => [v.name, v]))]));
const lit = (mode, name) => {
  const v = byName[mode].get(name);
  if (!v) throw new Error(`Unknown variable ${name}`);
  return v.literal;
};

// ─── variables-light.css / variables-dark.css ───────────────────────────────

function block(selector, list) {
  const lines = [`${selector} {`];
  grouped(list).forEach(([title, items], i) => {
    if (i) lines.push('');
    lines.push(`  /* ─── ${title} ─── */`);
    for (const v of items) lines.push(`  ${v.name}: ${v.value};`);
  });
  lines.push('}', '');
  return lines.join('\n');
}

const lightCss = HEADER('CSS custom properties (light, default)') + '\n' + block(':root', vars.light);

// A variable declared as var(--x) resolves where it is declared, and children
// inherit the result. So a .dark wrapper inside a light page must redeclare
// every variable whose resolved value changes, aliases included.
const darkChanged = vars.dark.filter((v) => byName.light.get(v.name).literal !== v.literal);
const darkCss = HEADER('CSS custom properties (dark)') +
  '\n/* Apply with class="dark" (shadcn) or data-theme="dark" on any element. */\n' +
  block('.dark,\n[data-theme="dark"]', darkChanged);

// ─── tailwind-theme.css ──────────────────────────────────────────────────────

const typeStyles = [...sets.light.values()].filter((t) => t.type === 'typography');
const styleName = (t) => t.path.split('.').pop();

// Tailwind's built-in text sizes, remapped onto the Fluent ramp so classes
// used inside shadcn components (text-sm, text-xs, ...) land on Proto-Lab sizes.
const TEXT_REMAP = {
  xs: 'caption-1', sm: 'body-1', base: 'body-2', lg: 'subtitle-1', xl: 'title-3',
  '2xl': 'title-2', '3xl': 'title-1', '4xl': 'large-title', '5xl': 'display',
};
const RADIUS_REMAP = {
  xs: 'small', sm: 'small', md: 'medium', lg: 'large', xl: 'x-large', '2xl': 'x-large', '3xl': 'x-large', '4xl': 'x-large',
};
const SHADOW_REMAP = { xs: '2', sm: '4', md: '8', lg: '16', xl: '28', '2xl': '64' };
const WEIGHTS = { light: 'light', normal: 'regular', regular: 'regular', medium: 'semibold', semibold: 'semibold', bold: 'bold' };

// Tailwind theme keys → the CSS variable each one is backed by (for docs).
const twIndex = {};
const tw = (key, value, backing) => {
  if (backing) (twIndex[backing] ||= []).push(key);
  return `  --${key}: ${value};`;
};

const colorAliases = vars.light.filter((v) => (v.path.startsWith('alias.') || /^color\.semantic\.(chart|illustration)\./.test(v.path)) && v.type === 'color');
const fluentColors = vars.light.filter((v) => /^color\.semantic\.(neutral|brand|status)\./.test(v.path));
const radii = vars.light.filter((v) => v.path.startsWith('corner-radius.'));
const elevations = vars.light.filter((v) => /^shadow\.\d+$/.test(v.path));
const easings = vars.light.filter((v) => v.path.startsWith('motion.easing.') && !v.path.endsWith('.linear'));

const themeCss = HEADER('Tailwind v4 theme') + `
/*
 * Proto-Lab owns color, type, weight, radius and shadow, so those Tailwind
 * namespaces are cleared and redefined. Everything else (breakpoints,
 * containers, tracking, leading, animation) keeps Tailwind's defaults, which
 * shadcn components rely on. Spacing stays Tailwind's 4px scale: it is the
 * Fluent grid (p-1 = xs 4px, p-2 = s 8px, p-3 = m 12px, p-4 = l 16px).
 *
 * Values that differ between light and dark live in @theme inline, so the
 * utility reads the variable at the element and a .dark wrapper works.
 */

@theme {
  --color-*: initial;
${tw('color-white', lit('light', '--color-white'))}
${tw('color-black', lit('light', '--color-black'))}

  --font-*: initial;
${tw('font-sans', lit('light', '--font-family'), '--font-family')}
${tw('font-mono', lit('light', '--font-family-mono'), '--font-family-mono')}

  --text-*: initial;
${Object.entries(TEXT_REMAP).map(([k, s]) => [
    tw(`text-${k}`, lit('light', `--font-size-${s}`), `--font-size-${s}`),
    tw(`text-${k}--line-height`, lit('light', `--line-height-${s}`)),
  ].join('\n')).join('\n')}
${typeStyles.map((t) => {
    const s = styleName(t);
    return [
      tw(`text-${s}`, lit('light', `--font-size-${s}`), `--font-size-${s}`),
      tw(`text-${s}--line-height`, lit('light', `--line-height-${s}`)),
      tw(`text-${s}--font-weight`, lit('light', `--font-weight-${s}`)),
    ].join('\n');
  }).join('\n')}

  --font-weight-*: initial;
${Object.entries(WEIGHTS).map(([k, w]) => tw(`font-weight-${k}`, lit('light', `--font-weight-${w}`), `--font-weight-${w}`)).join('\n')}

  --radius-*: initial;
${Object.entries(RADIUS_REMAP).map(([k, r]) => tw(`radius-${k}`, lit('light', `--radius-${r}`), `--radius-${r}`)).join('\n')}
${radii.map((v) => tw(v.name.slice(2), v.literal, v.name)).join('\n')}

  --shadow-*: initial;
${easings.map((v) => tw(`ease-${v.name.replace('--easing-', '')}`, v.literal, v.name)).join('\n')}
}

@theme inline {
${colorAliases.map((v) => tw(`color-${v.name.slice(2)}`, `var(${v.name})`, v.name)).join('\n')}

${fluentColors.map((v) => tw(`color-${v.name.slice(2)}`, `var(${v.name})`, v.name)).join('\n')}

${Object.entries(SHADOW_REMAP).map(([k, n]) => tw(`shadow-${k}`, `var(--shadow-${n})`, `--shadow-${n}`)).join('\n')}
${elevations.map((v) => tw(`shadow-elevation-${v.name.replace('--shadow-', '')}`, `var(${v.name})`, v.name)).join('\n')}
}
`;

// ─── proto-lab.css ───────────────────────────────────────────────────────────

const entryCss = HEADER('Tailwind entry') + `
/*
 * Import after Tailwind in your global stylesheet:
 *
 *   @import "tailwindcss";
 *   @import "tw-animate-css";
 *   @import "<design-system>/tokens/css/proto-lab.css";
 *
 * Projects without Tailwind import variables-light.css (and
 * variables-dark.css for dark mode) instead.
 */

@import "./variables-light.css";
@import "./variables-dark.css";
@import "./tailwind-theme.css";

@custom-variant dark (&:where(.dark, .dark *, [data-theme="dark"], [data-theme="dark"] *));

/* Fluent focus indicator: 2px ring with a 1px gap. */
@utility focus-ring {
  &:focus-visible {
    outline: var(--stroke-thick) solid var(--ring);
    outline-offset: var(--stroke-thin);
  }
}

@layer base {
  * {
    border-color: var(--border);
    outline-color: color-mix(in oklab, var(--ring) 50%, transparent);
  }
  body {
    background-color: var(--background);
    color: var(--foreground);
    font-size: var(--font-size-body-1);
    line-height: var(--line-height-body-1);
  }
}
`;

// ─── tokens.json ─────────────────────────────────────────────────────────────

const contrastResults = MODES.flatMap((mode) => PAIRS.pairs.map((p) => {
  const ratio = contrast(lit(mode, p.fg), lit(mode, p.bg), lit(mode, '--background'));
  return { mode, fg: p.fg, bg: p.bg, min: p.min, level: p.level, ratio: Math.round(ratio * 100) / 100, pass: ratio >= p.min };
}));

const tokensJson = JSON.stringify({
  $comment: 'GENERATED by packages/tokens/build.js from tokens/*.json. Do not edit.',
  modes: MODES,
  tokens: vars.light.map((v) => ({
    name: v.name,
    path: v.path,
    type: v.type,
    section: sectionOf(v),
    description: v.description || null,
    light: { value: v.value, literal: v.literal, chain: v.chain },
    dark: { value: byName.dark.get(v.name).value, literal: byName.dark.get(v.name).literal, chain: byName.dark.get(v.name).chain },
    tailwind: twIndex[v.name] || [],
  })),
  contrast: contrastResults,
}, null, 2) + '\n';

// ─── Skill reference (generated section of references/tokens.md) ────────────

const SKILL_REF = path.join(ROOT, '.github', 'skills', 'proto-lab-design-system', 'references', 'tokens.md');
const GEN_BEGIN = '<!-- generated:css-variables:begin -->';
const GEN_END = '<!-- generated:css-variables:end -->';

function skillSection() {
  const lines = [
    GEN_BEGIN,
    '## CSS Custom Properties',
    '',
    'Generated from `tokens/*.json`. Light values live in `tokens/css/variables-light.css`;',
    'dark overrides in `tokens/css/variables-dark.css` (apply with `class="dark"` or',
    '`data-theme="dark"`). Tailwind projects import `tokens/css/proto-lab.css`.',
  ];
  for (const [title, items] of grouped(vars.light)) {
    lines.push('', `### ${title}`, '| Variable | Light | Dark |', '|---|---|---|');
    for (const v of items) {
      const dark = byName.dark.get(v.name).literal;
      lines.push(`| \`${v.name}\` | ${v.literal} | ${dark === v.literal ? 'same' : dark} |`);
    }
  }
  lines.push(GEN_END);
  return lines.join('\n');
}

function skillRef(current) {
  const b = current.indexOf(GEN_BEGIN);
  const e = current.indexOf(GEN_END);
  if (b !== -1 && e !== -1) return current.slice(0, b) + skillSection() + current.slice(e + GEN_END.length);
  // First run: replace the hand-written CSS variable section.
  const start = current.indexOf('## CSS Custom Properties');
  const end = current.indexOf('## Component Registry');
  if (start === -1 || end === -1) throw new Error(`Cannot find the CSS variable section in ${SKILL_REF}`);
  return current.slice(0, start) + skillSection() + '\n\n' + current.slice(end);
}

// ─── Write or check ──────────────────────────────────────────────────────────

const outputs = [
  ['tokens/css/variables-light.css', lightCss],
  ['tokens/css/variables-dark.css', darkCss],
  ['tokens/css/tailwind-theme.css', themeCss],
  ['tokens/css/proto-lab.css', entryCss],
  ['tokens/dist/tokens.json', tokensJson],
  [path.relative(ROOT, SKILL_REF), skillRef(fs.readFileSync(SKILL_REF, 'utf8'))],
];

const check = process.argv.includes('--check');
let stale = 0;
for (const [rel, content] of outputs) {
  const file = path.join(ROOT, rel);
  const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (prev === content) { console.log(`  • ${rel} — up to date`); continue; }
  if (check) { console.log(`  ✗ ${rel} — stale`); stale++; continue; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log(`  ✓ ${rel}`);
}
if (stale) {
  console.error(`\n  ${stale} generated file(s) out of date. Run \`npm run tokens:build\`.\n`);
  process.exit(1);
}
