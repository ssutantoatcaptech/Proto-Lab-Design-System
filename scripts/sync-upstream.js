#!/usr/bin/env node
/**
 * sync-upstream.js
 *
 * Keeps Proto-Lab aligned with shadcn/ui (https://github.com/shadcn-ui/ui).
 *
 * Snapshot (default): installs every upstream Base UI "nova" component with the
 * pinned shadcn CLI into a scratch app initialized from @proto-lab/base, exactly
 * as a CapTech project would receive them, and writes them to
 * tooling/shadcn-sync/vendor/ui/. The snapshot is committed, so upstream
 * changes show up as a reviewable diff. The weekly upstream workflow runs this
 * and opens a pull request.
 *
 * Compare (--compare, no network): checks each Proto-Lab component in
 * apps/docs/registry/proto-lab/ui/ against the snapshot and writes
 * tooling/shadcn-sync/alignment.json, which the docs site renders.
 *
 * Usage:
 *   node scripts/sync-upstream.js             snapshot upstream, then compare
 *   node scripts/sync-upstream.js --compare   compare only
 *   node scripts/sync-upstream.js --check     compare and fail if alignment.json is stale
 */

'use strict';

const fs     = require('fs');
const os     = require('os');
const path   = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');

const ROOT     = path.resolve(__dirname, '..');
const DOCS     = path.join(ROOT, 'apps', 'docs');
const SYNC     = path.join(ROOT, 'tooling', 'shadcn-sync');
const VENDOR   = path.join(SYNC, 'vendor', 'ui');
const OURS     = path.join(DOCS, 'registry', 'proto-lab', 'ui');
const STYLE    = 'base-nova';
const UPSTREAM = `https://ui.shadcn.com/r/styles/${STYLE}`;
const CLI      = `shadcn@${require(path.join(DOCS, 'package.json')).devDependencies.shadcn}`;

const sha = (s) => crypto.createHash('sha256').update(s).digest('hex').slice(0, 12);
const run = (cmd, args, cwd) => execFileSync(cmd, args, {
  cwd, stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8', env: { ...process.env, CI: '1' },
});

// The CLI writes consumer aliases; the docs registry uses its own paths.
const toRegistryPaths = (src) => src
  .replaceAll('@/components/ui/', '@/registry/proto-lab/ui/')
  .replaceAll('@/lib/utils', '@/registry/proto-lab/lib/utils')
  .replaceAll('@/hooks/', '@/registry/proto-lab/hooks/');

async function snapshot() {
  const index = await (await fetch(`${UPSTREAM}/registry.json`)).json();
  const names = index.items.filter((i) => i.type === 'registry:ui').map((i) => i.name).sort();
  console.log(`  → ${names.length} upstream ${STYLE} components`);

  const app = fs.mkdtempSync(path.join(os.tmpdir(), 'proto-lab-upstream-'));
  try {
    fs.cpSync(path.join(ROOT, 'fixtures', 'vite-consumer'), app, { recursive: true });
    // The fixture's App imports components; the snapshot only needs a bare app.
    fs.writeFileSync(path.join(app, 'src', 'App.tsx'), 'export default function App() { return null }\n');
    console.log('  → npm install');
    run('npm', ['install', '--no-audit', '--no-fund'], app);
    console.log(`  → ${CLI} init @proto-lab/base, add all components`);
    run('npx', ['-y', CLI, 'init', path.join(DOCS, 'public', 'r', 'base.json'), '-y'], app);
    run('npx', ['-y', CLI, 'add', ...names, '-y', '--overwrite'], app);

    const installed = path.join(app, 'src', 'components', 'ui');
    fs.rmSync(VENDOR, { recursive: true, force: true });
    fs.mkdirSync(VENDOR, { recursive: true });
    const files = fs.readdirSync(installed).filter((f) => f.endsWith('.tsx')).sort();
    for (const f of files) fs.writeFileSync(path.join(VENDOR, f), toRegistryPaths(fs.readFileSync(path.join(installed, f), 'utf8')));

    const manifest = {
      $comment: 'GENERATED by scripts/sync-upstream.js. Upstream shadcn/ui components as a Proto-Lab project receives them.',
      upstream: 'https://github.com/shadcn-ui/ui',
      registry: `${UPSTREAM}/registry.json`,
      style: STYLE,
      cli: CLI,
      components: files.map((f) => {
        const src = fs.readFileSync(path.join(VENDOR, f), 'utf8');
        return { file: f, sha: sha(src) };
      }),
    };
    fs.writeFileSync(path.join(SYNC, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
    console.log(`  ✓ ${files.length} files in ${path.relative(ROOT, VENDOR)}`);
  } finally {
    fs.rmSync(app, { recursive: true, force: true });
  }
}

// The CLI adds "use client" only for React Server Component projects (the docs
// site is one, the snapshot app isn't). That's project config, not drift.
const normalize = (src) => src.replace(/^"use client"\n\n/, '')

function lineDiff(a, b) {
  // Lines present on one side only, ignoring order. Enough to size a drift.
  const count = (lines) => lines.reduce((m, l) => m.set(l, (m.get(l) || 0) + 1), new Map());
  const ca = count(a.split('\n')), cb = count(b.split('\n'));
  let added = 0, removed = 0;
  for (const [l, n] of cb) added += Math.max(0, n - (ca.get(l) || 0));
  for (const [l, n] of ca) removed += Math.max(0, n - (cb.get(l) || 0));
  return { added, removed };
}

function compare() {
  const manifest = JSON.parse(fs.readFileSync(path.join(SYNC, 'manifest.json'), 'utf8'));
  const upstream = manifest.components.map((c) => c.file);
  const ours = fs.readdirSync(OURS).filter((f) => f.endsWith('.tsx')).sort();
  const components = [...new Set([...upstream, ...ours])].sort().map((file) => {
    const name = file.replace(/\.tsx$/, '');
    const docs = `https://ui.shadcn.com/docs/components/${name}`;
    if (!ours.includes(file)) return { name, status: 'not-adopted', docs };
    if (!upstream.includes(file)) return { name, status: 'proto-lab-only', docs: null };
    const a = normalize(fs.readFileSync(path.join(VENDOR, file), 'utf8'));
    const b = normalize(fs.readFileSync(path.join(OURS, file), 'utf8'));
    if (a === b) return { name, status: 'matches', docs };
    return { name, status: 'differs', docs, ...lineDiff(a, b) };
  });
  const summary = components.reduce((m, c) => ({ ...m, [c.status]: (m[c.status] || 0) + 1 }), {});
  const alignment = {
    $comment: 'GENERATED by scripts/sync-upstream.js --compare. Proto-Lab components against the upstream snapshot.',
    upstream: manifest.upstream,
    style: manifest.style,
    cli: manifest.cli,
    summary,
    components,
  };
  return JSON.stringify(alignment, null, 2) + '\n';
}

async function main() {
  const mode = process.argv.includes('--check') ? 'check' : process.argv.includes('--compare') ? 'compare' : 'sync';
  if (mode === 'sync') await snapshot();
  const out = compare();
  const file = path.join(SYNC, 'alignment.json');
  const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  const s = JSON.parse(out).summary;
  console.log(`  ${s.matches || 0} match upstream, ${s.differs || 0} differ, ${s['not-adopted'] || 0} not adopted, ${s['proto-lab-only'] || 0} Proto-Lab only`);
  if (mode === 'check') {
    if (prev !== out) { console.error('  ✗ tooling/shadcn-sync/alignment.json is stale. Run `npm run upstream:compare`.'); process.exit(1); }
    console.log('  ✓ alignment.json is current');
    return;
  }
  fs.writeFileSync(file, out);
}

main().catch((e) => { console.error(`  ✗ ${e.message}`); process.exit(1); });
