#!/usr/bin/env node
/**
 * sync-charts.js
 *
 * Ports shadcn/ui's chart gallery (https://ui.shadcn.com/charts) to Proto-Lab.
 * Upstream publishes the 76 chart blocks only for the new-york-v4 style, but
 * each one depends on nothing more than card, chart, recharts and lucide, and
 * card and chart export the same components in base-nova. So the port is an
 * import rewrite, asserted for every file:
 *   @/registry/new-york-v4/ui/*  ->  @/registry/proto-lab/ui/*
 * Any other project import fails the sync.
 *
 * Writes apps/docs/registry/proto-lab/charts/:
 *   <name>.tsx             the chart, as upstream ships it
 *   index.ts               loaders for the docs gallery
 *   manifest.json          names, types and order
 *   registry-items.json    @proto-lab/chart-* items (merged by packages/tokens/build.js)
 *
 * Usage: node scripts/sync-charts.js [--check]
 */

'use strict';

const fs   = require('fs');
const path = require('path');

const ROOT     = path.resolve(__dirname, '..');
const OUT      = path.join(ROOT, 'apps', 'docs', 'registry', 'proto-lab', 'charts');
const OUT_REL  = 'registry/proto-lab/charts';
const UPSTREAM = 'https://ui.shadcn.com/r/styles/new-york-v4';
const TYPES    = ['area', 'bar', 'line', 'pie', 'radar', 'radial', 'tooltip'];
const HEADER   = '// Ported from shadcn/ui charts (new-york-v4) by scripts/sync-charts.js. Do not edit.\n';

const pascal = (s) => s.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const title = (name) => {
  const [, type, ...rest] = name.split('-');
  const variant = rest.join(' ') || 'default';
  return `${type[0].toUpperCase()}${type.slice(1)}: ${variant[0].toUpperCase()}${variant.slice(1)}`;
};

// Patches, each asserted. Base UI compatibility: upstream charts are written
// against the Radix Select:
// its onValueChange never passes null, and its trigger shows the item's label.
// Base UI's Select can pass null and needs `items` to show labels. Each patch
// must match exactly, so an upstream change fails the sync instead of slipping by.
const PATCHES = {
  'chart-area-interactive': [[
    '<Select value={timeRange} onValueChange={setTimeRange}>',
    '<Select\n          value={timeRange}\n          onValueChange={(value) => value && setTimeRange(value)}\n          items={[\n            { value: "90d", label: "Last 3 months" },\n            { value: "30d", label: "Last 30 days" },\n            { value: "7d", label: "Last 7 days" },\n          ]}\n        >',
  ]],
  // Upstream spreads Recharts' tick props onto <text>, including
  // verticalAnchor, which React rejects as an unknown DOM attribute.
  'chart-radar-label-custom': [[
    'tick={({ x, y, textAnchor, index, ...props }) => {',
    'tick={({ x, y, textAnchor, index, verticalAnchor: _verticalAnchor, ...props }) => {',
  ]],
  'chart-pie-interactive': [[
    '<Select value={activeMonth} onValueChange={setActiveMonth}>',
    '<Select\n          value={activeMonth}\n          onValueChange={(value) => value && setActiveMonth(value)}\n          items={months.map((key) => ({\n            value: key,\n            label: chartConfig[key as keyof typeof chartConfig]?.label ?? key,\n          }))}\n        >',
  ]],
};

function port(name, src) {
  let out = src.replaceAll('@/registry/new-york-v4/ui/', '@/registry/proto-lab/ui/');
  for (const [from, to] of PATCHES[name] || []) {
    if (!out.includes(from)) throw new Error(`${name}: Base UI patch no longer matches upstream: ${from}`);
    out = out.replace(from, to);
  }
  const stray = out.match(/from\s+["']@\/(?!registry\/proto-lab\/ui\/)[^"']+["']/g);
  if (stray) throw new Error(`${name}: unexpected import ${stray.join(', ')}`);
  return HEADER + out;
}

async function main() {
  const check = process.argv.includes('--check');
  const index = await (await fetch(`${UPSTREAM}/registry.json`)).json();
  const charts = index.items
    .filter((i) => i.name.startsWith('chart-') && TYPES.includes(i.name.split('-')[1]))
    .map((i) => ({ name: i.name, type: i.name.split('-')[1] }))
    .sort((a, b) => TYPES.indexOf(a.type) - TYPES.indexOf(b.type));

  const outputs = [];
  for (const c of charts) {
    const item = await (await fetch(`${UPSTREAM}/${c.name}.json`)).json();
    if (item.files.length !== 1) throw new Error(`${c.name}: expected one file, got ${item.files.length}`);
    const src = item.files[0].content;
    // Most charts export a named component; the -demo ones export default.
    const named = src.match(/export function (\w+)/);
    if (!named && !/export default function/.test(src)) throw new Error(`${c.name}: no exported component`);
    c.importClause = named ? `{ ${named[1]} as ${pascal(c.name)} }` : pascal(c.name);
    outputs.push([`${c.name}.tsx`, port(c.name, src)]);
  }

  const manifest = {
    $comment: 'GENERATED by scripts/sync-charts.js from shadcn/ui charts (new-york-v4).',
    types: TYPES.map((t) => ({ slug: t, count: charts.filter((c) => c.type === t).length })),
    charts: charts.map(({ name, type }) => ({ name, type, title: title(name), wide: /interactive/.test(name) })),
  };
  outputs.push(['manifest.json', JSON.stringify(manifest, null, 2) + '\n']);

  outputs.push(['index.ts', [
    '// GENERATED by scripts/sync-charts.js. Do not edit.',
    'import type { ComponentType } from "react"',
    '',
    ...charts.map((c) => `import ${c.importClause} from "./${c.name}"`),
    '',
    'export const charts: Record<string, ComponentType> = {',
    ...charts.map((c) => `  "${c.name}": ${pascal(c.name)},`),
    '}',
    '',
  ].join('\n')]);

  const items = charts.map((c) => ({
    name: c.name,
    type: 'registry:block',
    title: title(c.name),
    description: `Proto-Lab port of the shadcn/ui ${c.name} chart.`,
    registryDependencies: ['card', 'chart'],
    dependencies: ['recharts', 'lucide-react'],
    categories: ['charts', `charts-${c.type}`],
    files: [{ path: `${OUT_REL}/${c.name}.tsx`, type: 'registry:component', target: `components/charts/${c.name}.tsx` }],
  }));
  outputs.push(['registry-items.json', JSON.stringify(items, null, 2) + '\n']);

  let stale = 0;
  for (const [file, content] of outputs) {
    const p = path.join(OUT, file);
    const prev = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (prev === content) continue;
    if (check) { console.log(`  ✗ charts/${file} differs from upstream`); stale++; continue; }
    fs.mkdirSync(OUT, { recursive: true });
    fs.writeFileSync(p, content);
  }
  console.log(`  ${charts.length} charts: ${manifest.types.map((t) => `${t.slug} ${t.count}`).join(', ')}`);
  if (stale) process.exit(1);
}

main().catch((e) => { console.error(`  ✗ ${e.message}`); process.exit(1); });
