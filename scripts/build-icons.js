#!/usr/bin/env node
/**
 * build-icons.js
 *
 * Turns the CapTech illustrative icons in icons/<category>/*.svg into React
 * components for the shadcn registry (`@proto-lab/captech-icons`) and the docs
 * gallery. The SVGs stay the source; nothing written here is edited by hand.
 *
 *   apps/docs/registry/proto-lab/icons/illustration.tsx   shared <Illustration> wrapper
 *   apps/docs/registry/proto-lab/icons/<category>.tsx     one named export per icon
 *   apps/docs/registry/proto-lab/icons/index.ts           gallery index (docs only)
 *   apps/docs/registry/proto-lab/icons/registry-items.json  registry items, merged by packages/tokens/build.js
 *
 * Transform, asserted for every file:
 *   - #005EB8 and #FDDA24 become var(--illustration-primary|accent), with the
 *     hex as fallback, so icons follow dark mode. Any other color fails.
 *   - Full-size 48x48 clip paths (no-ops from the Figma export) are dropped.
 *     Real clip paths keep their shape with an id unique per instance.
 *
 * Usage:
 *   node scripts/build-icons.js           write outputs
 *   node scripts/build-icons.js --check   fail if any output is stale
 */

'use strict';

const fs   = require('fs');
const path = require('path');

const ROOT    = path.resolve(__dirname, '..');
const SRC     = path.join(ROOT, 'icons');
const OUT     = path.join(ROOT, 'apps', 'docs', 'registry', 'proto-lab', 'icons');
const OUT_REL = path.relative(path.join(ROOT, 'apps', 'docs'), OUT).split(path.sep).join('/');

const CATEGORIES = [
  { slug: 'general',           title: 'General' },
  { slug: 'practice-areas',    title: 'Practice areas' },
  { slug: 'core-values',       title: 'Core values' },
  { slug: 'core-competencies', title: 'Core competencies' },
  { slug: 'ergs',              title: 'ERGs' },
];

const COLORS = {
  '#005eb8': 'P', // illustration primary
  '#fdda24': 'A', // illustration accent
};

const HEADER = '// GENERATED by scripts/build-icons.js from icons/*.svg. Do not edit.\n';
const pascal = (slug) => slug.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const exportName = (slug) => `${pascal(slug)}Illustration`;

// ─── SVG → JSX ───────────────────────────────────────────────────────────────

const ATTR = {
  'fill-rule': 'fillRule', 'clip-rule': 'clipRule', 'clip-path': 'clipPath',
  'stroke-width': 'strokeWidth', 'stroke-miterlimit': 'strokeMiterlimit',
  'stroke-linecap': 'strokeLinecap', 'stroke-linejoin': 'strokeLinejoin',
};

function convert(file) {
  const svg = fs.readFileSync(file, 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();

  // Clip paths: map id → kept or dropped.
  const clips = new Map();
  for (const [, id, rect] of inner.matchAll(/<clipPath id="([^"]+)">\s*(<rect[^>]*\/>)\s*<\/clipPath>/g)) {
    const full = /width="48"/.test(rect) && /height="48"/.test(rect) && !/transform=/.test(rect);
    clips.set(id, { full, rect });
  }
  let kept = 0;
  const keptIds = new Map();
  for (const [id, c] of clips) if (!c.full) keptIds.set(id, `c${kept++}`);

  let body = inner
    // Drop <defs> entirely; kept clips are re-emitted below with unique ids.
    .replace(/<defs>[\s\S]*?<\/defs>/g, '')
    // Unwrap groups that only apply a no-op clip.
    .replace(/<g clip-path="url\(#([^)]+)\)">/g, (m, id) => {
      const c = clips.get(id);
      if (!c) throw new Error(`${file}: unknown clip ${id}`);
      return c.full ? '<g>' : `<g clip-path="url(#__ID__${keptIds.get(id)})">`;
    });

  body = body.replace(/(fill|stroke)="(#[0-9a-fA-F]{6})"/g, (m, prop, hex) => {
    const key = COLORS[hex.toLowerCase()];
    if (!key) throw new Error(`${file}: unexpected color ${hex}. Only CapTech Blue and Yellow are allowed.`);
    return `style={${prop === 'fill' ? 'F' : 'S'}${key}}`;
  });
  if (/#[0-9a-fA-F]{3,6}\b/.test(body)) throw new Error(`${file}: color left after transform`);
  // An element with both fill and stroke gets one merged style object.
  body = body.replace(/<[a-z]+\b[^>]*>/g, (tag) => {
    const styles = [...tag.matchAll(/ style=\{(\w+)\}/g)].map((m) => m[1]);
    if (styles.length < 2) return tag;
    return tag.replace(/ style=\{\w+\}/g, '').replace(/\s*(\/?>)$/, ` style={{ ${styles.map((s) => `...${s}`).join(', ')} }}$1`);
  });

  body = body
    .replace(/ ([a-z]+(?:-[a-z]+)+)=/g, (m, a) => {
      if (!ATTR[a]) throw new Error(`${file}: unmapped attribute ${a}`);
      return ` ${ATTR[a]}=`;
    })
    .replace(/clipPath="url\(#__ID__(c\d+)\)"/g, 'clipPath={`url(#${id}$1)`}')
    .replace(/\s*\n\s*/g, '\n      ')
    .trim();

  const defs = [...clips].filter(([, c]) => !c.full).map(([id, c]) =>
    `<clipPath id={\`\${id}${keptIds.get(id)}\`}>${c.rect.replace(' fill="white"', '')}</clipPath>`);

  return { body, defs };
}

// ─── Outputs ─────────────────────────────────────────────────────────────────

const illustrationTsx = `${HEADER}"use client"

import { useId } from "react"

export type IllustrationSize = 32 | 40 | 48 | 64 | 96

export type IllustrationProps = Omit<React.ComponentProps<"svg">, "children"> & {
  /** Rendered size in px. CapTech icons are illustrations: 32px is the minimum. */
  size?: IllustrationSize
  /** Accessible name. Without one the illustration is decorative and hidden from assistive tech. */
  title?: string
}

// Colors read the Proto-Lab illustration tokens, so they follow dark mode.
// The hex fallbacks keep icons on brand in a project without the theme.
export const FP = { fill: "var(--illustration-primary, #005eb8)" }
export const FA = { fill: "var(--illustration-accent, #fdda24)" }
export const SP = { stroke: "var(--illustration-primary, #005eb8)" }
export const SA = { stroke: "var(--illustration-accent, #fdda24)" }

export function Illustration({
  size = 48,
  title,
  children,
  ...props
}: IllustrationProps & { children: (id: string) => React.ReactNode }) {
  const id = useId().replace(/:/g, "")
  return (
    <svg
      viewBox="0 0 48 48"
      width={size}
      height={size}
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      focusable="false"
      data-slot="illustration"
      {...props}
    >
      {title && <title>{title}</title>}
      {children(id)}
    </svg>
  )
}
`;

const outputs = [[path.join(OUT, 'illustration.tsx'), illustrationTsx]];
const index = [];
const items = [];
let total = 0;

for (const cat of CATEGORIES) {
  const files = fs.readdirSync(path.join(SRC, cat.slug)).filter((f) => f.endsWith('.svg')).sort();
  const comps = [];
  const styles = new Set();
  for (const f of files) {
    const slug = f.replace(/\.svg$/, '');
    const { body, defs } = convert(path.join(SRC, cat.slug, f));
    for (const m of body.matchAll(/(?:\{|\.\.\.)([FS][PA])\b/g)) styles.add(m[1]);
    const name = exportName(slug);
    comps.push(
      `export function ${name}(props: IllustrationProps) {\n` +
      `  return (\n    <Illustration {...props}>\n      {(${defs.length ? 'id' : '_'}) => (\n        <>\n      ${body}` +
      (defs.length ? `\n      <defs>${defs.join('')}</defs>` : '') +
      `\n        </>\n      )}\n    </Illustration>\n  )\n}\n`
    );
    index.push({ slug, name, category: cat.slug });
    total++;
  }
  const imports = ['Illustration', 'type IllustrationProps', ...[...styles].sort()].join(', ');
  const tsx = `${HEADER}"use client"\n\nimport { ${imports} } from "./illustration"\n\n${comps.join('\n')}`;
  outputs.push([path.join(OUT, `${cat.slug}.tsx`), tsx]);

  items.push({
    name: `captech-icons-${cat.slug}`,
    type: 'registry:component',
    title: `CapTech icons: ${cat.title}`,
    description: `${files.length} CapTech illustrative icons (${cat.title}). Illustrations only, never interface icons.`,
    files: [
      { path: `${OUT_REL}/illustration.tsx`, type: 'registry:component', target: 'components/captech-icons/illustration.tsx' },
      { path: `${OUT_REL}/${cat.slug}.tsx`, type: 'registry:component', target: `components/captech-icons/${cat.slug}.tsx` },
    ],
  });
}

items.unshift({
  name: 'captech-icons',
  type: 'registry:component',
  title: 'CapTech icons',
  description: `All ${total} CapTech illustrative icons. Illustrations only, never interface icons.`,
  files: [
    { path: `${OUT_REL}/illustration.tsx`, type: 'registry:component', target: 'components/captech-icons/illustration.tsx' },
    ...CATEGORIES.map((c) => ({ path: `${OUT_REL}/${c.slug}.tsx`, type: 'registry:component', target: `components/captech-icons/${c.slug}.tsx` })),
  ],
});

const indexTs = `${HEADER}// Gallery index for the docs site. Not part of any registry item.
import type { ComponentType } from "react"
import type { IllustrationProps } from "./illustration"
${CATEGORIES.map((c) => `import * as ${pascal(c.slug)} from "./${c.slug}"`).join('\n')}

export const categories = ${JSON.stringify(CATEGORIES.map((c) => ({ slug: c.slug, title: c.title })), null, 2)} as const

const modules: Record<string, Record<string, unknown>> = {
${CATEGORIES.map((c) => `  "${c.slug}": ${pascal(c.slug)},`).join('\n')}
}

export type IconEntry = { slug: string; name: string; category: string; Component: ComponentType<IllustrationProps> }

export const icons: IconEntry[] = ${JSON.stringify(index.map(({ slug, name, category }) => ({ slug, name, category })), null, 2)}.map((i) => ({
  ...i,
  Component: modules[i.category][i.name] as ComponentType<IllustrationProps>,
}))
`;

outputs.push([path.join(OUT, 'index.ts'), indexTs]);
outputs.push([path.join(OUT, 'registry-items.json'), JSON.stringify(items, null, 2) + '\n']);

// ─── Write or check ──────────────────────────────────────────────────────────

const check = process.argv.includes('--check');
let stale = 0;
for (const [file, content] of outputs) {
  const rel = path.relative(ROOT, file);
  const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (prev === content) { console.log(`  • ${rel} — up to date`); continue; }
  if (check) { console.log(`  ✗ ${rel} — stale`); stale++; continue; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log(`  ✓ ${rel}`);
}
console.log(`\n  ${total} icons in ${CATEGORIES.length} categories\n`);
if (stale) {
  console.error(`  ${stale} generated icon file(s) out of date. Run \`npm run icons:build\`.\n`);
  process.exit(1);
}
